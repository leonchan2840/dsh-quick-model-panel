'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const read = name => fs.readFileSync(path.join(root, name), 'utf8').replace(/\r\n/g, '\n');
// 不打入另一份 React/ReactDOM；由实际 DSH loader 解析宿主实例。
function buildClient() {
  const bundleModule = name => `(function(){const module={exports:{}};\n${read('src/' + name + '.cjs')}\nreturn module.exports;})()`;
  const view = JSON.parse(read('src/view-locales.json')), host = JSON.parse(read('src/host-locales.json'));
  const dict = Object.fromEntries(Object.keys(view).map(lang => [lang, { ...view[lang], ...host[lang] }]));
  return `// Generated by build.cjs. Edit src/ rather than this file.\nwindow.__ModuleLoader__.load({\n  id: '@local/dsh-quick-model-panel',\n  factory(require) {\n    const React = require('react');\n    const { createPortal } = require('react-dom');\n    const logic = ${bundleModule('logic')};\n    const { createView } = ${bundleModule('view')};\n    const { createPlugin } = ${bundleModule('host-view')};\n    return createPlugin(React, createPortal, {...logic, createView}, ${JSON.stringify(dict)}, ${JSON.stringify(read('src/panel.css'))});\n  }\n});\n`;
}
if (require.main === module) fs.writeFileSync(path.join(root, 'client.js'), buildClient(), 'utf8');
module.exports = { buildClient };
